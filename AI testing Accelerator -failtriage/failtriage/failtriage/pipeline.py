"""Glue: parse -> cluster -> classify -> report + audit log."""
from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from pathlib import Path

from . import rules
from .clusterer import cluster
from .llm import ClaudeTriager
from .models import Category, Cluster, Failure


def triage(failures: list[Failure], engine: str = "claude", run_context: dict | None = None,
           triager: ClaudeTriager | None = None, audit_path: Path | None = None) -> tuple[list[Cluster], dict]:
    t0 = time.time()
    clusters = cluster(failures)
    if engine == "claude" and triager is None:
        triager = ClaudeTriager()
    audit_rows = []
    for c in clusters:
        meta: dict = {}
        if engine == "rules":
            c.verdict = rules.classify_cluster(c)
        else:
            try:
                c.verdict, meta = triager.classify(c, run_context)
            except Exception as e:  # never lose a run because the API hiccuped
                c.verdict = rules.classify_cluster(c)
                c.verdict.needs_human_review = True
                c.verdict.reason = f"[LLM unavailable: {type(e).__name__}: {e}] " + c.verdict.reason
                meta = {"error": f"{type(e).__name__}: {e}", "fallback": "rules"}
        audit_rows.append({
            "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "cluster_id": c.cluster_id,
            "tests": c.test_ids,
            "signature": c.signature,
            "verdict": c.verdict.to_dict(),
            **meta,
        })
    stats = {
        "failures": len(failures),
        "clusters": len(clusters),
        "engine": engine,
        "elapsed_s": round(time.time() - t0, 2),
        "needs_review": sum(1 for c in clusters if c.verdict.needs_human_review),
        "by_category": {cat: sum(len(c.failures) for c in clusters if c.verdict.category == cat)
                        for cat in Category.values()},
    }
    if triager is not None:
        stats["usage"] = dict(triager.usage)
    if audit_path:
        audit_path.parent.mkdir(parents=True, exist_ok=True)
        with audit_path.open("a") as fh:
            for row in audit_rows:
                fh.write(json.dumps(row) + "\n")
    return clusters, stats


ICON = {"PRODUCT_BUG": "🐞", "TEST_BUG": "🧪", "ENVIRONMENT": "🌩️", "FLAKY": "🎲"}


def render_ticket(c: Cluster) -> str:
    v = c.verdict
    tests = "\n".join(f"- `{t}`" for t in c.test_ids)
    evidence = "\n".join(f"- `{e}`" for e in v.evidence) or "- (none)"
    body = v.jira_description or v.reason
    return (
        f"> **DRAFT — generated by failtriage ({v.engine}). A human must review before filing.**\n\n"
        f"# {v.jira_summary or c.signature[:100]}\n\n"
        f"| Field | Value |\n|---|---|\n"
        f"| Triage category | {v.category} |\n"
        f"| Confidence | {v.confidence:.2f}{' — **needs human review**' if v.needs_human_review else ''} |\n"
        f"| Suggested owner | {v.suggested_owner or '-'} |\n"
        f"| Failure group | {c.cluster_id} ({len(c.failures)} tests) |\n\n"
        f"## Description\n{body}\n\n"
        f"## Why this category\n{v.reason}\n\n"
        f"## Evidence\n{evidence}\n\n"
        f"## Affected tests\n{tests}\n"
    )


def render_report(clusters: list[Cluster], stats: dict, title: str) -> str:
    lines = [
        f"# Triage report — {title}",
        "",
        f"**{stats['failures']} failed tests → {stats['clusters']} distinct issues** "
        f"(engine: `{stats['engine']}`, {stats['elapsed_s']}s, "
        f"{stats['needs_review']} flagged for human review)",
        "",
        "| Category | Failed tests |",
        "|---|---|",
    ]
    for cat, n in stats["by_category"].items():
        lines.append(f"| {ICON[cat]} {cat} | {n} |")
    if "usage" in stats:
        u = stats["usage"]
        lines += ["", f"LLM calls: {u['calls']} (cache hits {u['cache_hits']}), "
                      f"tokens in/out: {u['input_tokens']}/{u['output_tokens']}"]
    lines += ["", "## Issues (largest first)", "",
              "| # | Group | Tests | Category | Conf. | Review? | Summary |",
              "|---|---|---|---|---|---|---|"]
    for i, c in enumerate(clusters, 1):
        v = c.verdict
        summary = (v.jira_summary or v.reason).replace("|", "/")[:90]
        lines.append(f"| {i} | {c.cluster_id} | {len(c.failures)} | {ICON[v.category]} {v.category} | "
                     f"{v.confidence:.2f} | {'⚠️ yes' if v.needs_human_review else 'no'} | {summary} |")
    lines += ["", "Ticket drafts are in `tickets/`. Every decision is logged in `audit.jsonl`."]
    return "\n".join(lines) + "\n"


def write_outputs(clusters: list[Cluster], stats: dict, out_dir: Path, title: str) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "tickets").mkdir(exist_ok=True)
    for i, c in enumerate(clusters, 1):
        (out_dir / "tickets" / f"{i:02d}_{c.verdict.category}_{c.cluster_id}.md").write_text(render_ticket(c))
    (out_dir / "triage_report.md").write_text(render_report(clusters, stats, title))
    (out_dir / "triage_result.json").write_text(json.dumps({
        "stats": stats,
        "clusters": [{"cluster_id": c.cluster_id, "signature": c.signature, "tests": c.test_ids,
                      "verdict": c.verdict.to_dict()} for c in clusters],
    }, indent=2, ensure_ascii=False))
